// bench/report.ts — reads bench/results/<date>.json (or latest) and writes
// bench/results/report.md (README table) + bench/results/chart.svg.
// Usage: npx tsx bench/report.ts [--file <path>]
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { arg } from "../scripts/args.js";

const fileArg = arg("file");
const files = readdirSync("bench/results")
  .filter((f) => f.endsWith(".json"))
  .sort();
const file =
  fileArg ??
  (files.length > 0 ? `bench/results/${files[files.length - 1]}` : null);
if (!file) {
  console.error("report: no results JSON (run bench/run.ts first)");
  process.exit(1);
}
const res = JSON.parse(readFileSync(file, "utf8")) as {
  date: string;
  seed: number;
  quick: boolean;
  live: boolean;
  conditions: Record<
    string,
    {
      runs: number;
      sfr: string;
      sfrCI: string[];
      cvr: string;
      cvrCI: string[];
      fbr: string;
      fbrCI: string[];
      recovery: string;
      honestFailure: string;
      injection: string;
      latencyMs: { p50: number; p95: number };
    }
  >;
};
const f = res.conditions.forge;
const b = res.conditions.baseline;
const row = (label: string, a: string, c: string): string =>
  `| ${label} | ${a} | ${c} |`;
const md = [
  `<!-- generated by bench/report.ts from ${file}; do not hand-edit -->`,
  `| Metric | ContextForge | Baseline (memory only) |`,
  `|---|---|---|`,
  row(
    "Silent-failure rate",
    `${f.sfr} (95% CI ${f.sfrCI.join("–")})`,
    `${b.sfr} (95% CI ${b.sfrCI.join("–")})`,
  ),
  row(
    "Constraint-violation rate",
    `${f.cvr} (95% CI ${f.cvrCI.join("–")})`,
    `${b.cvr} (95% CI ${b.cvrCI.join("–")})`,
  ),
  row(
    "False-block rate",
    `${f.fbr} (95% CI ${f.fbrCI.join("–")})`,
    `${b.fbr} (95% CI ${b.fbrCI.join("–")})`,
  ),
  row("Fault recovery", f.recovery, b.recovery),
  row("Honest failures", f.honestFailure, b.honestFailure),
  row("Injection success", f.injection, b.injection),
  row(
    "Latency p50/p95 (S1)",
    `${f.latencyMs.p50}/${f.latencyMs.p95} ms`,
    `${b.latencyMs.p50}/${b.latencyMs.p95} ms`,
  ),
  ``,
  `_L1 oracle harness, seed ${res.seed}${res.quick ? " (quick)" : ""}, ${res.date}. ` +
    `Oracle = always-right-tool + report-what-the-tool-says (models acknowledgment-trusting behavior, not real Alexa+). ` +
    `Limitations: twin != devices; ontology = heuristics; see docs/BENCHMARK.md._`,
  ``,
].join("\n");

const pctOf = (s: string): number => Number(s.split("%")[0]) || 0;
const bars: [string, number, string][] = [
  ["Forge SFR", pctOf(f.sfr), "#146c2e"],
  ["Baseline SFR", pctOf(b.sfr), "#b3261e"],
  ["Forge CVR", pctOf(f.cvr), "#146c2e"],
  ["Baseline CVR", pctOf(b.cvr), "#b3261e"],
];
const W = 520;
const BH = 28;
const H = bars.length * (BH + 10) + 30;
const max = Math.max(1, ...bars.map(([, v]) => v));
let y = 10;
let rects = "";
for (const [label, v, color] of bars) {
  const w = Math.max(2, Math.round((v / max) * 380));
  rects += `<text x="10" y="${y + 19}" font-size="13" font-family="system-ui">${label} ${v.toFixed(1)}%</text>`;
  rects += `<rect x="150" y="${y}" width="${w}" height="${BH}" fill="${color}"/>`;
  y += BH + 10;
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" role="img" aria-label="benchmark rates">${rects}</svg>`;

writeFileSync("bench/results/report.md", md);
writeFileSync("bench/results/chart.svg", svg);
console.log(`wrote bench/results/report.md + chart.svg from ${file}`);
